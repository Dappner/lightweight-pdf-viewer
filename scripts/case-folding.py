#!/usr/bin/env python3
"""Generates src/case_folding.rs from Unicode's CaseFolding.txt (full folding: statuses C and F).

    scripts/case-folding.py [CaseFolding.txt]   # downloads Unicode 18.0.0 if no file is given
"""
import sys
import urllib.request

URL = "https://www.unicode.org/Public/18.0.0/ucd/CaseFolding.txt"  # keep in step with src/case_folding.rs

text = open(sys.argv[1]).read() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()
version = text.splitlines()[0].lstrip("# ").strip()
folds = []
for line in text.splitlines():
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    code, status, mapping = [f.strip() for f in line.split(";")[:3]]
    if status in ("C", "F"):
        folds.append((int(code, 16), "".join(chr(int(c, 16)) for c in mapping.split())))
folds.sort()


def rust(s):
    return "".join(c if c.isascii() and c.isprintable() and c not in '"\\' else f"\\u{{{ord(c):X}}}" for c in s)


out = [
    f"//! Unicode full case folding (statuses C and F), from {version}.",
    "//! Generated by `scripts/case-folding.py`; don't edit by hand.",
    "//! Unicode data © Unicode, Inc., under the Unicode License v3: https://www.unicode.org/license.txt",
    "",
    "/// Characters and what they fold to, sorted by character.",
    "pub static FOLDS: &[(char, &str)] = &[",
]
out += [f'    (\'\\u{{{code:X}}}\', "{rust(mapping)}"),' for code, mapping in folds]
out += ["];", ""]
open("src/case_folding.rs", "w").write("\n".join(out))
print(f"{len(folds)} folds from {version}")
